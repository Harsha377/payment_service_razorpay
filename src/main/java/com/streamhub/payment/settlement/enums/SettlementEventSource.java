package com.streamhub.payment.settlement.enums;

public enum SettlementEventSource {

    SYSTEM,
    PAYMENT,
    SCHEDULER,
    ADMIN
}

/*

| Source      | Description                                         |
| ----------- | --------------------------------------------------- |
| `SYSTEM`    | Generated by the Settlement module itself.          |
| `PAYMENT`   | Triggered automatically after a successful payment. |
| `SCHEDULER` | Triggered by a scheduled or retry job.              |
| `ADMIN`     | Triggered manually by an administrator.             |

* */