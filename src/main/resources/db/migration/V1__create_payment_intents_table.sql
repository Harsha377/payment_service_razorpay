CREATE TABLE payment_intents
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    payment_intent_reference VARCHAR(26) NOT NULL,

    order_reference VARCHAR(26) NOT NULL,

    customer_reference VARCHAR(26) NOT NULL,

    amount BIGINT NOT NULL,

    currency VARCHAR(3) NOT NULL,

    status VARCHAR(30) NOT NULL,

    description VARCHAR(255),

    metadata JSONB,

    expires_at TIMESTAMP WITH TIME ZONE,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payment_intents
        PRIMARY KEY (id),

    CONSTRAINT uk_payment_intents_reference
        UNIQUE (payment_intent_reference),

    CONSTRAINT ck_payment_intents_amount
        CHECK (amount > 0),

    CONSTRAINT ck_payment_intents_currency
        CHECK (
            currency = UPPER(currency)
                AND char_length(currency) = 3
            )
);

CREATE INDEX idx_payment_intents_order_reference
    ON payment_intents(order_reference);

CREATE INDEX idx_payment_intents_customer_reference
    ON payment_intents(customer_reference);

CREATE INDEX idx_payment_intents_status
    ON payment_intents(status);