CREATE TABLE payment_events
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_event_reference VARCHAR(26) NOT NULL,

    payment_id BIGINT NOT NULL,

    event_type VARCHAR(50) NOT NULL,

    event_source VARCHAR(50) NOT NULL,

    event_data JSONB,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payment_events
        PRIMARY KEY (id),
    CONSTRAINT uk_payment_events_reference
        UNIQUE(payment_event_reference),

    CONSTRAINT fk_payment_events_payments
        FOREIGN KEY (payment_id)
            REFERENCES payments(id)
            ON DELETE RESTRICT,

    CONSTRAINT ck_payment_events_event_type
        CHECK (trim(event_type) <> ''),

    CONSTRAINT ck_payment_events_event_source
        CHECK (trim(event_source) <> '')
);

CREATE INDEX idx_payment_events_payment_created
    ON payment_events(payment_id, created_at);