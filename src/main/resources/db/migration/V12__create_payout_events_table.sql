CREATE TABLE payout_events(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    payout_event_reference VARCHAR(26) NOT NULL ,
    payout_id BIGINT NOT NULL ,
    event_type VARCHAR(50) NOT NULL ,
    event_source VARCHAR(50) NOT NULL ,
    event_data JSONB NOT NULL ,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT  uk_payout_event_reference UNIQUE  (payout_event_reference),
    CONSTRAINT fk_payout_event_payout FOREIGN KEY (payout_id) REFERENCES payouts(id)
);


CREATE INDEX idx_payout_event_payout
    ON payout_events(payout_id);

CREATE INDEX idx_payout_event_type
    ON payout_events(event_type);