CREATE TABLE settlements
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,

    settlement_reference VARCHAR(26)              NOT NULL,

    payment_id           BIGINT                   NOT NULL,

    beneficiary_id       BIGINT                   NOT NULL,

    wallet_id            BIGINT                   NOT NULL,

    gross_amount         BIGINT                   NOT NULL,

    commission_amount    BIGINT                   NOT NULL DEFAULT 0,

    net_amount           BIGINT                   NOT NULL,

    currency             VARCHAR(3)               NOT NULL,

    status               VARCHAR(30)              NOT NULL,

    metadata             JSONB,

    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_settlements
        PRIMARY KEY (id),

    CONSTRAINT uk_settlement_reference
        UNIQUE (settlement_reference),

    CONSTRAINT uk_settlement_payment
        UNIQUE (payment_id),

    CONSTRAINT fk_settlement_payment
        FOREIGN KEY (payment_id)
            REFERENCES payments (id),

    CONSTRAINT fk_settlement_beneficiary
        FOREIGN KEY (beneficiary_id)
            REFERENCES beneficiaries (id),

    CONSTRAINT fk_settlement_wallet
        FOREIGN KEY (wallet_id)
            REFERENCES wallets (id),

    CONSTRAINT chk_settlement_gross_amount
        CHECK (gross_amount > 0),

    CONSTRAINT chk_settlement_commission_amount
        CHECK (commission_amount >= 0),

    CONSTRAINT chk_settlement_net_amount
        CHECK (net_amount >= 0),

    CONSTRAINT chk_settlement_currency
        CHECK (
            currency = UPPER(currency)
                AND char_length(currency) = 3
            )
);

CREATE INDEX idx_settlement_reference
    ON settlements(settlement_reference);

CREATE INDEX idx_settlement_payment
    ON settlements(payment_id);

CREATE INDEX idx_settlement_beneficiary
    ON settlements(beneficiary_id);

CREATE INDEX idx_settlement_wallet
    ON settlements(wallet_id);

CREATE INDEX idx_settlement_status
    ON settlements(status);

CREATE INDEX idx_settlement_created_at
    ON settlements(created_at);