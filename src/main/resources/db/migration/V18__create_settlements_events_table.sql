CREATE TABLE settlement_events
(

    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY,

    settlement_event_reference VARCHAR(26)              NOT NULL,

    settlement_id              BIGINT                   NOT NULL,

    event_type                 VARCHAR(50)              NOT NULL,

    event_source               VARCHAR(30)              NOT NULL,

    event_data                 JSONB,

    created_at                 TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_settlement_events
        PRIMARY KEY (id),

    CONSTRAINT uk_settlement_event_reference
        UNIQUE (settlement_event_reference),

    CONSTRAINT fk_settlement_event_settlement
        FOREIGN KEY (settlement_id)
            REFERENCES settlements (id)
);

CREATE INDEX idx_settlement_event_reference
    ON settlement_events(settlement_event_reference);

CREATE INDEX idx_settlement_event_settlement
    ON settlement_events(settlement_id);

CREATE INDEX idx_settlement_event_type
    ON settlement_events(event_type);

CREATE INDEX idx_settlement_event_created_at
    ON settlement_events(created_at);