CREATE TABLE payments
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    payment_reference VARCHAR(26) NOT NULL,

    payment_intent_id BIGINT NOT NULL,

    gateway_name VARCHAR(50) NOT NULL,

    gateway_order_id VARCHAR(255) NOT NULL,

    gateway_payment_id VARCHAR(255),

    gateway_signature VARCHAR(512),

    amount BIGINT NOT NULL,

    currency VARCHAR(3) NOT NULL,

    payment_method VARCHAR(50),

    status VARCHAR(30) NOT NULL,

    gateway_status VARCHAR(50),

    gateway_response JSONB,

    paid_at TIMESTAMP WITH TIME ZONE,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payments
        PRIMARY KEY (id),

    CONSTRAINT uk_payments_reference
        UNIQUE (payment_reference),

    CONSTRAINT uk_payments_gateway_order_id
        UNIQUE (gateway_order_id),

    CONSTRAINT uk_payments_gateway_payment_id
        UNIQUE (gateway_payment_id),

    CONSTRAINT fk_payments_payment_intents
        FOREIGN KEY (payment_intent_id)
            REFERENCES payment_intents(id)
            ON DELETE RESTRICT,

    CONSTRAINT ck_payments_amount
        CHECK (amount > 0),

    CONSTRAINT ck_payments_currency
        CHECK (
            currency = UPPER(currency)
                AND char_length(currency) = 3
            )
);

CREATE INDEX idx_payments_status
    ON payments(status);

CREATE INDEX idx_payments_created_at
    ON payments(created_at);

CREATE INDEX idx_payments_payment_intent_id
    ON payments(payment_intent_id);